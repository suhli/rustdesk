import { writeFileSync } from 'node:fs';

const taps = ['topLeft', 'top', 'topRight', 'left', 'center', 'right', 'bottomLeft', 'bottom', 'bottomRight'];
const hiddenCount = 8;
let seed = 1;
function random() {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 2 ** 32;
}

function example() {
  const theta = random() * Math.PI;
  const slopeX = Math.cos(theta);
  const slopeY = Math.sin(theta);
  const offset = random() * 2 - 1;
  const thickness = 0.15 + random() * 0.7;
  const kind = Math.floor(5 * random());
  const foreground = random();
  const background = random();
  const gradient = (random() - 0.5) * 0.15;
  function pattern(x, y) {
    const distance = x * slopeX + y * slopeY - offset;
    const tests = [distance < 0, Math.abs(distance) < thickness,
      Math.abs(x - offset) < thickness || Math.abs(y + offset) < thickness,
      x > offset && y < -offset, Math.abs(x - offset) < thickness && Math.abs(y + offset) < thickness];
    return Math.min(1, Math.max(0, (tests[kind] ? foreground : background) + x * gradient));
  }
  const high = [];
  for (let y = 0; y < 6; y++) {
    for (let x = 0; x < 6; x++) {
      let value = 0;
      for (const dy of [0.125, 0.375]) {
        for (const dx of [0.125, 0.375]) value += pattern((x - 3) / 2 + dx, (y - 3) / 2 + dy);
      }
      high.push(value / 4);
    }
  }
  const input = [];
  const levels = random() < 0.5 ? 63 : 255;
  for (let y = 0; y < 6; y += 2) {
    for (let x = 0; x < 6; x += 2) {
      const pos = y * 6 + x;
      const average = (high[pos] + high[pos + 1] + high[pos + 6] + high[pos + 7]) / 4;
      input.push(Math.round(average * levels) / levels);
    }
  }
  const target = [];
  for (let y = 0; y < 2; y++) {
    for (let x = 0; x < 2; x++) {
      const horizontal = x === 0 ? -1 : 1;
      const vertical = y === 0 ? -3 : 3;
      const linear = (9 * input[4] + 3 * (input[4 + horizontal] + input[4 + vertical]) +
        input[4 + horizontal + vertical]) / 16;
      target.push(high[(y + 2) * 6 + x + 2] - linear);
    }
  }
  return { input, target };
}

const filters = Array.from({ length: hiddenCount }, () => [...taps.map(() => random() * 0.6 - 0.3), 0.1]);
const output = Array.from({ length: 4 }, () => [...filters.map(() => random() * 0.15 - 0.075), 0]);
const training = Array.from({ length: 18000 }, example);
const sum = (values, weights) => values.reduce((total, value, i) => total + value * weights[i], weights[values.length]);

for (let epoch = 0; epoch < 30; epoch++) {
  const rate = 0.022 / (1 + epoch / 10);
  for (const { input, target } of training) {
    const activations = filters.map(filter => Math.max(0, sum(input, filter)));
    const errors = output.map((weights, i) => sum(activations, weights) - target[i]);
    for (let h = 0; h < hiddenCount; h++) {
      if (activations[h] === 0) continue;
      const gradient = errors.reduce((result, value, i) => result + value * output[i][h], 0);
      for (let j = 0; j < taps.length; j++) filters[h][j] -= rate * gradient * input[j];
      filters[h][taps.length] -= rate * gradient;
    }
    for (let i = 0; i < output.length; i++) {
      for (let h = 0; h < hiddenCount; h++) output[i][h] -= rate * errors[i] * activations[h];
      output[i][hiddenCount] -= rate * errors[i];
    }
  }
}

let baseline = 0;
let enhanced = 0;
for (let sample = 0; sample < 4000; sample++) {
  const { input, target } = example();
  const activations = filters.map(filter => Math.max(0, sum(input, filter)));
  for (let i = 0; i < target.length; i++) {
    const correction = Math.max(-0.24, Math.min(0.24, sum(activations, output[i])));
    baseline += target[i] ** 2;
    enhanced += (correction - target[i]) ** 2;
  }
}
console.log(`Synthetic holdout MSE: bilinear ${(baseline / 16000).toFixed(6)}, model ${(enhanced / 16000).toFixed(6)}`);
if (!(enhanced < baseline * 0.95)) throw new Error('Model failed the synthetic holdout check');

const f = value => value.toFixed(7);
const vec4 = values => `vec4(${values.map(f).join(', ')})`;
const layers = filters.map((weights, i) => {
  return `  float hidden${i} = max(0.0, ${f(weights[9])}\n` +
    `      + dot(${vec4(weights.slice(0, 4))}, vec4(${taps.slice(0, 4).join(', ')}))\n` +
    `      + dot(${vec4(weights.slice(4, 8))}, vec4(${taps.slice(4, 8).join(', ')}))\n` +
    `      + (${f(weights[8])}) * ${taps[8]});`;
});
const weights = filters.map((_, i) => `      + hidden${i} * ${vec4(output.map(row => row[i]))}`);
const shader = `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/train_mobile_super_resolution.mjs.
#include <flutter/runtime_effect.glsl>

uniform vec2 imageSize;
uniform vec4 region;
uniform sampler2D frame;
out vec4 fragColor;

vec3 rgbAt(vec2 pos) {
  vec2 first = region.xy + vec2(0.5);
  vec2 last = region.xy + region.zw - vec2(0.5);
  return texture(frame, clamp(pos, first, last) / imageSize).rgb;
}

void main() {
  vec2 pos = region.xy + FlutterFragCoord().xy * 0.5;
  vec2 centerPixel = floor(pos) + vec2(0.5);
  const vec3 luma = vec3(0.2126, 0.7152, 0.0722);
${taps.map((tap, index) =>
  `  vec3 rgb${index} = rgbAt(centerPixel + vec2(${index % 3 - 1}.0, ${Math.floor(index / 3) - 1}.0));\n` +
  `  float ${tap} = dot(rgb${index}, luma);`).join('\n')}
${layers.join('\n')}
  vec4 residual = ${vec4(output.map(row => row[hiddenCount]))}
${weights.join('\n')};
  vec2 subpixel = fract(pos);
  bool leftSide = subpixel.x < 0.5;
  bool topSide = subpixel.y < 0.5;
  float correction = topSide ? (leftSide ? residual.x : residual.y) : (leftSide ? residual.z : residual.w);
  vec3 horizontal = leftSide ? rgb3 : rgb5;
  vec3 vertical = topSide ? rgb1 : rgb7;
  vec3 diagonal = topSide ? (leftSide ? rgb0 : rgb2) : (leftSide ? rgb6 : rgb8);
  vec3 linear = (9.0 * rgb4 + 3.0 * (horizontal + vertical) + diagonal) / 16.0;
  fragColor = vec4(clamp(linear + vec3(clamp(correction, -0.24, 0.24)), 0.0, 1.0), 1.0);
}
`;
writeFileSync(new URL('../flutter/shaders/mobile_super_resolution.frag', import.meta.url), shader);
